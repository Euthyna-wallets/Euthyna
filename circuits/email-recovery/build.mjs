// Compile the circuit (nargo 1.0.0-beta.26) and publish what the app needs:
//   apps/console/public/circuits/email_recovery.json  the circuit, for proving in the browser
//   packages/sdk/src/email-recovery-vk.ts              its verification key, for the API and the browser check
//   contracts/email-recovery/src/vk.bin                the same key, built into the recovery contract
// The key is for zero-knowledge proofs with a Keccak transcript (bb's "evm" target), the
// format the on-chain verifier reads.
// Usage: node circuits/email-recovery/build.mjs   (needs nargo 1.0.0-beta.26 in $NARGO or ~/.nargo/bin)
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const nargo = process.env.NARGO ?? join(homedir(), ".nargo/bin/nargo");
execFileSync(nargo, ["compile"], { cwd: here, stdio: "inherit" });
const circuitPath = join(here, "target/email_recovery.json");
const circuit = JSON.parse(readFileSync(circuitPath, "utf8"));
mkdirSync(join(root, "apps/console/public/circuits"), { recursive: true });
copyFileSync(circuitPath, join(root, "apps/console/public/circuits/email_recovery.json"));

const { Barretenberg, UltraHonkBackend } = await import(join(root, "apps/api/node_modules/@aztec/bb.js/dest/node/index.js"));
const api = await Barretenberg.new({ threads: 1 });
const vk = await new UltraHonkBackend(circuit.bytecode, api).getVerificationKey({ verifierTarget: "evm" });
await api.destroy();
writeFileSync(join(root, "contracts/email-recovery/src/vk.bin"), vk);
const bytecodeHash = createHash("sha256").update(circuit.bytecode).digest("hex");
writeFileSync(join(root, "packages/sdk/src/email-recovery-vk.ts"), `// Generated by circuits/email-recovery/build.mjs: do not edit.
/** sha256 of the compiled circuit's bytecode this key belongs to. */
export const EMAIL_RECOVERY_BYTECODE_SHA256 = "${bytecodeHash}";
/** UltraHonk verification key of circuits/email-recovery (bb.js 5.3.0, zero-knowledge, Keccak transcript: "evm"). */
export const EMAIL_RECOVERY_VK_BASE64 = "${Buffer.from(vk).toString("base64")}";
`);
console.log(`circuit ${bytecodeHash}, vk ${vk.length} bytes`);
process.exit(0);
