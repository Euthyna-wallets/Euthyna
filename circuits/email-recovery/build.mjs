// Compile the circuit (nargo 1.0.0-beta.5) and publish what the app needs:
//   apps/console/public/circuits/email_recovery.json  the circuit, for proving in the browser
//   packages/sdk/src/email-recovery-vk.ts              its verification key, for the API and the browser check
// Usage: node circuits/email-recovery/build.mjs   (needs nargo on PATH or in ~/.nargo/bin)
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../..");
const nargo = process.env.NARGO ?? join(homedir(), ".nargo/bin/nargo");
execFileSync(nargo, ["compile"], { cwd: here, stdio: "inherit" });
const circuitPath = join(here, "target/email_recovery.json");
const circuit = JSON.parse(readFileSync(circuitPath, "utf8"));
mkdirSync(join(root, "apps/console/public/circuits"), { recursive: true });
copyFileSync(circuitPath, join(root, "apps/console/public/circuits/email_recovery.json"));

const { UltraHonkBackend } = await import(join(root, "apps/api/node_modules/@aztec/bb.js/dest/node/index.js"));
const vk = await new UltraHonkBackend(circuit.bytecode, { threads: 1 }).getVerificationKey();
const bytecodeHash = createHash("sha256").update(circuit.bytecode).digest("hex");
writeFileSync(join(root, "packages/sdk/src/email-recovery-vk.ts"), `// Generated by circuits/email-recovery/build.mjs: do not edit.
/** sha256 of the compiled circuit's bytecode this key belongs to. */
export const EMAIL_RECOVERY_BYTECODE_SHA256 = "${bytecodeHash}";
/** UltraHonk verification key of circuits/email-recovery (bb.js 0.84.0). */
export const EMAIL_RECOVERY_VK_BASE64 = "${Buffer.from(vk).toString("base64")}";
`);
console.log(`circuit ${bytecodeHash}, vk ${vk.length} bytes`);
process.exit(0);
